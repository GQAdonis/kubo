// Generates src/contract/generated/*.ts from mcp/contract. Pure function of the
// contract files: generate() returns { relativePath: content } and never writes.

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pascal, toZod } from './schema-to-zod.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const UI_ROOT = resolve(here, '..', '..');
export const CONTRACT_ROOT = resolve(UI_ROOT, '..', 'contract');

const HEADER = (src) =>
  `// GENERATED by scripts/gen-contract.mjs from mcp/contract (${src}). Do not edit.\n// Regenerate with \`pnpm gen:contract\`; tests fail when this file drifts from the contract.\n`;

const readJson = (rel) => {
  const text = readFileSync(join(CONTRACT_ROOT, rel), 'utf8');
  return { json: JSON.parse(text), text };
};

const CONFIRMATION_DEFS = [
  'ConfirmationClass',
  'Target',
  'Resolver',
  'ConfirmationId',
  'Summary',
  'ConfirmationRequired',
  'PendingConfirmation',
  'Outcome',
];

function refsOf(node, acc = new Set()) {
  if (Array.isArray(node)) node.forEach((n) => refsOf(n, acc));
  else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string') acc.add(v);
      else refsOf(v, acc);
    }
  }
  return acc;
}

function topo(defs, localPrefix) {
  const order = [];
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    for (const ref of refsOf(defs[name])) {
      if (ref.startsWith(localPrefix)) {
        const dep = ref.slice(localPrefix.length);
        if (dep in defs) visit(dep);
      }
    }
    order.push(name);
  };
  Object.keys(defs).forEach(visit);
  return order;
}

function genConfirmation() {
  const { json } = readJson('confirmation/confirmation.schema.json');
  const defs = Object.fromEntries(CONFIRMATION_DEFS.map((n) => [n, json.$defs[n]]));
  const resolve = (ref) => {
    if (!ref.startsWith('#/$defs/')) throw new Error(`confirmation: unexpected $ref ${ref}`);
    const name = ref.slice('#/$defs/'.length);
    if (!CONFIRMATION_DEFS.includes(name)) throw new Error(`confirmation: $ref to ungenerated def ${name}`);
    return `${name}Schema`;
  };
  let out = HEADER('confirmation/confirmation.schema.json') + "import { z } from 'zod';\n\n";
  for (const name of topo(defs, '#/$defs/')) {
    out += `export const ${name}Schema = ${toZod(defs[name], resolve, `confirmation#/${name}`)};\n`;
    out += `export type ${name} = z.infer<typeof ${name}Schema>;\n\n`;
  }
  return out;
}

function genCommon() {
  const { json } = readJson('schemas/common.json');
  const defs = json.$defs;
  const resolve = (ref) => {
    if (ref.startsWith('#/$defs/')) return `${ref.slice('#/$defs/'.length)}Schema`;
    const m = /^\.\.\/confirmation\/confirmation\.schema\.json#\/\$defs\/(\w+)$/.exec(ref);
    if (m) {
      if (!CONFIRMATION_DEFS.includes(m[1])) throw new Error(`common: $ref to ungenerated confirmation def ${m[1]}`);
      return `K.${m[1]}Schema`;
    }
    throw new Error(`common: unexpected $ref ${ref}`);
  };
  let out = HEADER('schemas/common.json') + "import { z } from 'zod';\nimport * as K from './confirmation';\n\n";
  for (const name of topo(defs, '#/$defs/')) {
    out += `export const ${name}Schema = ${toZod(defs[name], resolve, `common#/${name}`)};\n`;
    out += `export type ${name} = z.infer<typeof ${name}Schema>;\n\n`;
  }
  return out;
}

function genOutputs(catalog) {
  const resolve = (ref) => {
    let m = /^\.\.\/common\.json#\/\$defs\/(\w+)$/.exec(ref);
    if (m) return `C.${m[1]}Schema`;
    m = /^\.\.\/\.\.\/confirmation\/confirmation\.schema\.json#\/\$defs\/(\w+)$/.exec(ref);
    if (m) return `K.${m[1]}Schema`;
    throw new Error(`outputs: unexpected $ref ${ref}`);
  };
  let out =
    HEADER('schemas/tools/*.output.json') +
    "import { z } from 'zod';\nimport * as C from './common';\nimport * as K from './confirmation';\n\n";
  const names = [];
  for (const tool of catalog.tools) {
    const { json } = readJson(tool.outputSchema);
    const id = `${pascal(tool.name)}Output`;
    names.push([tool.name, id]);
    out += `export const ${id}Schema = ${toZod(json, resolve, tool.outputSchema)};\n`;
    out += `export type ${id} = z.infer<typeof ${id}Schema>;\n\n`;
  }
  out += `export const TOOL_OUTPUT_SCHEMAS = {\n${names.map(([n, id]) => `  ${n}: ${id}Schema,`).join('\n')}\n} as const;\n\n`;
  out += 'export type ToolOutputMap = {\n' + names.map(([n, id]) => `  ${n}: ${id};`).join('\n') + '\n};\n';
  return out;
}

const AGUI_DEFS = ['Id', 'Message', 'Interrupt'];

function genAgui() {
  const { json } = readJson('fixtures/agui.schema.json');
  const defs = Object.fromEntries(AGUI_DEFS.map((n) => [n, json.$defs[n]]));
  const resolve = (ref) => {
    if (!ref.startsWith('#/$defs/')) throw new Error(`agui: unexpected $ref ${ref}`);
    const name = ref.slice('#/$defs/'.length);
    if (!AGUI_DEFS.includes(name)) throw new Error(`agui: $ref to ungenerated def ${name}`);
    return `Agui${name}Schema`;
  };
  let out = HEADER('fixtures/agui.schema.json') + "import { z } from 'zod';\n\n";
  for (const name of topo(defs, '#/$defs/')) {
    out += `export const Agui${name}Schema = ${toZod(defs[name], resolve, `agui#/${name}`)};\n`;
    out += `export type Agui${name} = z.infer<typeof Agui${name}Schema>;\n\n`;
  }
  return out;
}

const CHAT_RULE =/^(always|copy:(contentEgress|returnsUntrustedContent)|not-equal:confirmation:none)$/;

function genMeta(catalog, a2ui, digest) {
  const tools = catalog.tools.map((t) => ({
    name: t.name,
    group: t.group,
    title: t.title,
    confirmation: t.confirmation,
    returnsUntrustedContent: t.returnsUntrustedContent,
    contentEgress: t.contentEgress,
    paginated: t.paginated,
    component: t.ui?.a2uiComponent ?? null,
    appView: t.ui?.appView ?? null,
    summaryTemplate: t.confirmationSummary ?? null,
  }));
  const componentNames = new Set(a2ui.components.map((c) => c.name));
  for (const t of tools) {
    if (t.component && !componentNames.has(t.component)) {
      throw new Error(`catalog: tool ${t.name} binds unknown a2uiComponent ${t.component}`);
    }
  }
  for (const [k, rule] of Object.entries(a2ui.chatRules)) {
    if (!CHAT_RULE.test(rule)) throw new Error(`a2ui-components: chat rule ${k} has an unsupported form: ${rule}`);
  }
  const lit = (v) => JSON.stringify(v, null, 2);
  let out = HEADER('catalog.json, derivations/a2ui-components.json');
  out += `\nexport const CONTRACT_VERSION = ${JSON.stringify(catalog.contractVersion)};\n`;
  out += `export const CONTRACT_DIGEST = ${JSON.stringify(digest)};\n`;
  const aliases = a2ui.catalogAliases ?? [];
  if (!aliases.length) throw new Error('a2ui-components: catalogAliases is empty; the short catalog name comes from it');
  out += `export const A2UI_CATALOG_ID = ${JSON.stringify(a2ui.catalogId)};\n`;
  out += `export const A2UI_CATALOG_ALIASES = ${JSON.stringify(aliases)} as const;\n`;
  out += `export const A2UI_CATALOG_SHORT_NAME = ${JSON.stringify(aliases[0])};\n\n`;
  out += `export type ToolName = ${tools.map((t) => JSON.stringify(t.name)).join(' | ')};\n\n`;
  out += 'export type ConfirmationLevel = "none" | "write" | "destructive";\n\n';
  out += 'export interface ToolMeta {\n  readonly name: ToolName;\n  readonly group: string;\n  readonly title: string;\n  readonly confirmation: ConfirmationLevel;\n  readonly returnsUntrustedContent: boolean;\n  readonly contentEgress: boolean;\n  readonly paginated: boolean;\n  readonly component: ComponentName | null;\n  readonly appView: string | null;\n  readonly summaryTemplate: string | null;\n}\n\n';
  out += `export type ComponentName = ${a2ui.components.map((c) => JSON.stringify(c.name)).join(' | ')};\n\n`;
  out += `export const TOOL_META: Record<ToolName, ToolMeta> = ${lit(Object.fromEntries(tools.map((t) => [t.name, t])))};\n\n`;
  out += `export const COMPONENT_META = ${lit(a2ui.components)} as const;\n\n`;
  out += `export const CHAT_RULES = ${lit(a2ui.chatRules)} as const;\n`;
  return out;
}

function genBindings(catalog, a2ui) {
  const byComponent = new Map(a2ui.components.filter((c) => c.kind === 'view').map((c) => [c.name, []]));
  for (const t of catalog.tools) {
    const c = t.ui?.a2uiComponent;
    if (c) byComponent.get(c)?.push(t.name);
  }
  let out =
    HEADER('catalog.json ui bindings') +
    "import { z } from 'zod';\nimport * as O from './outputs';\nimport type { ComponentName, ToolName } from './tool-meta';\n\n";
  const lines = [];
  for (const [component, tools] of byComponent) {
    if (tools.length === 0) {
      lines.push(`// ${component}: no tool binds it; its data is hand-composed from the confirmation schemas.\n`);
      continue;
    }
    const members = tools
      .map((t) => `  z.strictObject({ tool: z.literal(${JSON.stringify(t)}), output: O.${pascal(t)}OutputSchema }),`)
      .join('\n');
    lines.push(
      `export const ${component}DataSchema = z.discriminatedUnion('tool', [\n${members}\n]);\nexport type ${component}Data = z.infer<typeof ${component}DataSchema>;\nexport const ${component}Tools = ${JSON.stringify(tools)} as const;\n`,
    );
  }
  out += lines.join('\n');
  out += `\nexport const VIEW_TOOLS: Readonly<Partial<Record<ComponentName, readonly ToolName[]>>> = {\n${[...byComponent]
    .filter(([, t]) => t.length)
    .map(([c, t]) => `  ${c}: ${JSON.stringify(t)},`)
    .join('\n')}\n};\n`;
  return out;
}

export function generate() {
  const cat = readJson('catalog.json');
  const a2ui = readJson('derivations/a2ui-components.json');
  const digest = createHash('sha256').update(cat.text).update(a2ui.text).digest('hex').slice(0, 16);
  return {
    'src/contract/generated/confirmation.ts': genConfirmation(),
    'src/contract/generated/common.ts': genCommon(),
    'src/contract/generated/agui.ts': genAgui(),
    'src/contract/generated/outputs.ts': genOutputs(cat.json),
    'src/contract/generated/tool-meta.ts': genMeta(cat.json, a2ui.json, digest),
    'src/contract/generated/bindings.ts': genBindings(cat.json, a2ui.json),
  };
}
