    console.log('no key, new host: Test', await state('Test connection'), '| note', await page.eval(`document.querySelector('#as-test-note').textContent`))
    for (const v of [dark(D), light(M)]) await shot(page, 'e7-no-key-test-open', v, { selector: '[data-id="AgentSettingsConfirm"]', offset: v.width < 500 ? 200 : 160 })
    await page.clickText('button', 'Test connection')
    await page.until(text('answered in'), 20000)
    await sleep(400)
    console.log('result text:', await page.eval(`document.querySelector('.as-test [aria-live]').innerText`))
    for (const v of [dark(D)]) await shot(page, 'e8-no-key-test-result', v, { selector: '.as-test', offset: 160 })
