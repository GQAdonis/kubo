#!/usr/bin/env python3
"""Generate and check docs/mcp/config-reference.md.

The reference is generated from two inputs:

- mcp/contract/config/ipfs-mcp-config.schema.json: every key with its type,
  default, offSwitch, ownerChange, flag and env annotations (the contract is
  the source of truth);
- docs/mcp/config-reference.tests.json: for every key, option, environment
  variable and build tag, the Go tests that run it in its off or default
  state, plus notes where this build differs from the schema description.

Usage, from the repository root:

  python3 docs/mcp/config_reference.py --write
      regenerate docs/mcp/config-reference.md

  python3 docs/mcp/config_reference.py --check --ipfs cmd/ipfs/ipfs
      fail (exit 1) when the file is stale, when a schema key, an option of
      `ipfs mcp` or one of its subcommands (from --help of the given binary),
      or an IPFS_MCP_* variable read by non-test code is undocumented, when the
      sidecar names a key, option or variable that does not exist, or when a
      named test function does not exist.

Standard library only.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCHEMA = os.path.join(ROOT, "mcp/contract/config/ipfs-mcp-config.schema.json")
SIDECAR = os.path.join(ROOT, "docs/mcp/config-reference.tests.json")
OUT = os.path.join(ROOT, "docs/mcp/config-reference.md")
TEST_DIRS = ["mcp", "test/cli", "cmd/ipfs/kubo"]
CODE_DIRS = ["mcp/server", "cmd/ipfs/kubo"]
# Variables that are not operator settings: the macOS prompt passes these to
# its own /usr/bin/swift child process.
INTERNAL_ENV = {"IPFS_MCP_LA_REASON", "IPFS_MCP_LA_PROBE"}
SUBCOMMANDS = ["ipfs mcp", "ipfs mcp check-uar", "ipfs mcp confirm", "ipfs mcp pair"]


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def walk(node, path, out):
    """Collect (path, schema) for every property, depth first, in file order."""
    for name, sub in node.get("properties", {}).items():
        p = f"{path}.{name}" if path else name
        out.append((p, sub))
        walk(sub, p, out)
        items = sub.get("items")
        if isinstance(items, dict) and "properties" in items:
            walk(items, p + "[]", out)
            # principals[] entries: report the array's children under "principals[]".
    return out


def type_of(s):
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    t = s.get("type")
    if isinstance(t, list):
        return " or ".join(t)
    if t == "array" and isinstance(s.get("items"), dict):
        it = s["items"]
        inner = it.get("$ref", "").rsplit("/", 1)[-1] or it.get("type") or ("enum" if "enum" in it else "any")
        return f"array of {inner}"
    if t is None and "anyOf" in s:
        return " or ".join(type_of(a) for a in s["anyOf"])
    if t is None and "enum" in s:
        return "enum"
    return t or "any"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def fmt_default(v):
    if v is None:
        return "none"
    return "`" + json.dumps(v) + "`"


def tests_cell(tests):
    return ", ".join(f"`{t}`" for t in tests)


DEFAULTS = os.path.join(ROOT, "docs/mcp/defaults-table.json")
CHAT_SETUP = os.path.join(ROOT, "docs/mcp/chat-setup.md")
D_BEGIN = "<!-- defaults-table:begin (generated by docs/mcp/config_reference.py from docs/mcp/defaults-table.json) -->"
D_END = "<!-- defaults-table:end -->"


def render_defaults(table, level):
    """The fork's default-on features as a markdown table with a resource note."""
    out = ["| Feature | Where it is on | Off switch | Disabled-state test |", "|---|---|---|---|"]
    for r in table["rows"]:
        out.append("| " + " | ".join(cell(r[k]) for k in ("feature", "on", "off", "tests")) + " |")
    out += ["", table["note"], "", "Resource use: " + table["resource"]]
    return "\n".join(out)


def splice_chat_setup(text, table):
    """Replace the block between the defaults-table markers, or return None if absent."""
    i, j = text.find(D_BEGIN), text.find(D_END)
    if i < 0 or j < i:
        return None
    return text[:i] + D_BEGIN + "\n\n" + render_defaults(table, 3) + "\n\n" + text[j:]


def render(schema, side):
    keys = walk(schema, "", [])
    lines = []
    w = lines.append
    w("# `ipfs mcp` configuration reference")
    w("")
    w("<!-- Generated by docs/mcp/config_reference.py from mcp/contract/config/ipfs-mcp-config.schema.json and docs/mcp/config-reference.tests.json. Do not edit by hand: change the schema or the sidecar and run `python3 docs/mcp/config_reference.py --write`. -->")
    w("")
    w("Every setting of `ipfs mcp`: the config file keys, the command-line options, the environment variables and the build tags, each with its default, its off switch and the tests that run it in that state. For how to use them, see the [user guide](user-guide.md), the [agentic guide](agentic.md), the [embeddings guide](embeddings.md) and the [chat setup](chat-setup.md).")
    w("")
    w("None of these is a Kubo repo config key. `ipfs mcp` never reads or writes `$IPFS_PATH/config`, and nothing here appears in [`docs/config.md`](../config.md). The config file is a separate JSON file named by `--mcp-config=<path>` or `IPFS_MCP_CONFIG` (the flag wins); without either, no file is read and every key takes its default. The root `--config` flag keeps its Kubo meaning. The file is validated against the schema at start, unknown keys are rejected, and credentials are always references (`{\"env\": \"NAME\"}` or `{\"file\": \"/absolute/path\"}`), never literal values. No key has a default network endpoint.")
    w("")
    w("Precedence: a command-line option wins over its environment variable, which wins over the config file, which wins over the default.")
    w("")
    w("## Features enabled by default in this fork")
    w("")
    w(render_defaults(load(DEFAULTS), 3))
    w("")
    w("## Contents")
    w("")
    w("- [Features enabled by default in this fork](#features-enabled-by-default-in-this-fork)")
    w("- [Config file keys](#config-file-keys)")
    w("- [Command-line options](#command-line-options)")
    w("- [Environment variables](#environment-variables)")
    w("- [Build tags](#build-tags)")
    w("- [Value types](#value-types)")
    w("")
    w("## Config file keys")
    w("")
    sections = [p for p, _ in keys if "." not in p and "[" not in p]
    for top in sections:
        w(f"### `{top}`")
        w("")
        w("| Key | Type | Default | Flag or variable | Off switch | Tests (off or default state) |")
        w("|---|---|---|---|---|---|")
        for p, s in keys:
            if p != top and not p.startswith(top + ".") and not p.startswith(top + "[]"):
                continue
            entry = side["keys"].get(p, {"tests": []})
            fe = []
            if s.get("flag"):
                fe.append(", ".join(f"`{x.strip()}`" for x in s["flag"].split(",")))
            if s.get("env"):
                fe.append(f"`{s['env']}`")
            off = s.get("offSwitch", "")
            if entry.get("note"):
                off = off + " **This build:** " + entry["note"]
            w(f"| `{p}` | {cell(type_of(s))} | {cell(fmt_default(s.get('default')))} | {cell('; '.join(fe)) or '-'} | {cell(off)} | {tests_cell(entry['tests'])} |")
        w("")
    w("## Command-line options")
    w("")
    w("Global options such as `--api` and `--api-auth` keep their Kubo meaning (see `ipfs --help`); `ipfs mcp` uses them to reach the daemon. Give the RPC secret with `--api-auth-env` or `--api-auth-file` instead of `--api-auth`, which puts it in the process list (`ipfs mcp` warns when it is used). In a build with the `noagent` tag the `--llm-*`, `--agui` and `--a2a` options do not exist.")
    w("")
    for cmd in SUBCOMMANDS:
        opts = side["options"][cmd]
        w(f"### `{cmd}`")
        w("")
        if not opts:
            w("No options.")
            w("")
            continue
        w("| Option | Config key | Meaning, default and off switch | Tests |")
        w("|---|---|---|---|")
        for name, o in opts.items():
            if o.get("key"):
                ks = dict(keys)[o["key"]]
                meaning = f"Same as `{o['key']}`. Default {fmt_default(ks.get('default'))}. Off: {ks.get('offSwitch', '')}"
                key = f"`{o['key']}`"
            else:
                meaning, key = o["doc"], "-"
            w(f"| `{name}` | {key} | {cell(meaning)} | {tests_cell(o['tests'])} |")
        w("")
    w("## Environment variables")
    w("")
    w("| Variable | Meaning | Tests |")
    w("|---|---|---|")
    for name, e in side["env"].items():
        w(f"| `{name}` | {cell(e['doc'])} | {tests_cell(e['tests'])} |")
    w("")
    w("Credential references in the config file name further variables of your choosing (for example `IPFS_MCP_UI_TOKEN`); they are read only when the key that names them is set.")
    w("")
    w("## Build tags")
    w("")
    w("| Tag | Effect | Tests |")
    w("|---|---|---|")
    for name, b in side["buildTags"].items():
        w(f"| `{name}` | {cell(b['doc'])} | {tests_cell(b['tests'])} |")
    w("")
    w("## Value types")
    w("")
    w("| Type | Rule |")
    w("|---|---|")
    for name, d in schema.get("$defs", {}).items():
        desc = d.get("description", "")
        if not desc:
            if "pattern" in d:
                desc = f"String matching `{d['pattern']}`."
            elif "enum" in d:
                desc = "One of " + ", ".join(f"`{x}`" for x in d["enum"]) + "."
            else:
                desc = type_of(d)
        w(f"| `{name}` | {cell(desc)} |")
    w("")
    return "\n".join(lines)


def test_functions():
    names = set()
    pat = re.compile(r"^func (Test\w+)\(", re.M)
    for d in TEST_DIRS:
        for base, _, files in os.walk(os.path.join(ROOT, d)):
            if "node_modules" in base:
                continue
            for f in files:
                if f.endswith("_test.go"):
                    with open(os.path.join(base, f), encoding="utf-8") as fh:
                        names.update(pat.findall(fh.read()))
    return names


def code_env_vars():
    found = set()
    pat = re.compile(r'"(IPFS_MCP_[A-Z0-9_]+)"')
    for d in CODE_DIRS:
        for base, _, files in os.walk(os.path.join(ROOT, d)):
            for f in files:
                if not f.endswith(".go") or f.endswith("_test.go"):
                    continue
                with open(os.path.join(base, f), encoding="utf-8") as fh:
                    src = fh.read()
                if re.search(r"^//go:build .*mcptestresolver", src, re.M) and "!mcptestresolver" not in src:
                    continue
                found.update(pat.findall(src))
    return found - INTERNAL_ENV


def help_options(binary, cmd):
    args = [binary] + cmd.split()[1:] + ["--help"]
    out = subprocess.run(args, capture_output=True, text=True, timeout=60).stdout
    m = re.search(r"^OPTIONS\n(.*?)(?:^\S|\Z)", out, re.S | re.M)
    if not m:
        return set()
    return set(re.findall(r"^\s{2}(--[a-z0-9-]+)\s", m.group(1), re.M))


def check(schema, side, binary):
    errs = []
    keys = [p for p, _ in walk(schema, "", [])]
    for p in keys:
        if p not in side["keys"]:
            errs.append(f"schema key not documented in the sidecar: {p}")
    for p in side["keys"]:
        if p not in keys:
            errs.append(f"sidecar names a key the schema lacks: {p}")
    tests = test_functions()
    def need(where, names):
        if not names:
            errs.append(f"{where}: no test named")
        for t in names:
            if t not in tests:
                errs.append(f"{where}: test {t} does not exist")
    for p, e in side["keys"].items():
        need(f"key {p}", e.get("tests", []))
    for cmd, opts in side["options"].items():
        for name, o in opts.items():
            need(f"{cmd} {name}", o.get("tests", []))
            if o.get("key") and o["key"] not in keys:
                errs.append(f"{cmd} {name}: key {o['key']} not in schema")
            if not o.get("key") and not o.get("doc"):
                errs.append(f"{cmd} {name}: neither key nor doc")
    for name, e in side["env"].items():
        need(f"env {name}", e.get("tests", []))
    for name, b in side["buildTags"].items():
        need(f"build tag {name}", b.get("tests", []))
    env_code = code_env_vars()
    for v in sorted(env_code - set(side["env"])):
        errs.append(f"environment variable read by non-test code is undocumented: {v}")
    for v in sorted(set(side["env"]) - env_code):
        errs.append(f"sidecar documents an environment variable no code reads: {v}")
    for p, s in walk(schema, "", []):
        if s.get("env") and s["env"] not in side["env"]:
            errs.append(f"schema key {p} names env {s['env']} which is not documented")
    if binary:
        for cmd in SUBCOMMANDS:
            have = help_options(binary, cmd)
            doc = set(side["options"].get(cmd, {}))
            for o in sorted(have - doc):
                errs.append(f"`{cmd} --help` has {o}, which the reference lacks")
            for o in sorted(doc - have):
                errs.append(f"the reference documents {cmd} {o}, which `{cmd} --help` lacks")
    want = render(schema, side)
    try:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != want + "\n":
                errs.append(f"{os.path.relpath(OUT, ROOT)} is stale: run python3 docs/mcp/config_reference.py --write")
    except FileNotFoundError:
        errs.append(f"{os.path.relpath(OUT, ROOT)} is missing")
    try:
        with open(CHAT_SETUP, encoding="utf-8") as f:
            cur = f.read()
        if splice_chat_setup(cur, load(DEFAULTS)) != cur:
            errs.append(f"the defaults table in {os.path.relpath(CHAT_SETUP, ROOT)} is stale or its markers are missing: run python3 docs/mcp/config_reference.py --write")
    except FileNotFoundError:
        errs.append(f"{os.path.relpath(CHAT_SETUP, ROOT)} is missing")
    return errs, len(keys), len(tests)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--ipfs", help="ipfs binary whose `mcp --help` is compared (default: none, help not compared)")
    a = ap.parse_args()
    schema, side = load(SCHEMA), load(SIDECAR)
    if a.write:
        missing = [p for p, _ in walk(schema, "", []) if p not in side["keys"]]
        if missing:
            sys.exit("sidecar lacks keys: " + ", ".join(missing))
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(render(schema, side) + "\n")
        print(f"wrote {os.path.relpath(OUT, ROOT)}")
        with open(CHAT_SETUP, encoding="utf-8") as f:
            cur = f.read()
        new = splice_chat_setup(cur, load(DEFAULTS))
        if new is None:
            sys.exit("docs/mcp/chat-setup.md lacks the defaults-table markers")
        with open(CHAT_SETUP, "w", encoding="utf-8") as f:
            f.write(new)
        print(f"wrote the defaults table in {os.path.relpath(CHAT_SETUP, ROOT)}")
    if a.check:
        errs, nkeys, ntests = check(schema, side, a.ipfs)
        opts = sum(len(v) for v in side["options"].values())
        print(f"schema keys: {nkeys}; options: {opts}; env: {len(side['env'])}; build tags: {len(side['buildTags'])}; test functions found: {ntests}; --help compared: {'yes (' + a.ipfs + ')' if a.ipfs else 'no'}")
        for e in errs:
            print("FAIL:", e)
        if errs:
            sys.exit(1)
        print("OK: config-reference.md matches the schema, the sidecar and --help")
    if not (a.write or a.check):
        ap.print_help()


if __name__ == "__main__":
    main()
